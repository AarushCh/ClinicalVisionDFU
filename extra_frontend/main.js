  function initNavSpy() {
    const links = [...document.querySelectorAll(".lab-nav a[href^='#']")];
    if (!links.length) return;

    const sections = links
      .map((a) => document.getElementById(a.getAttribute("href").slice(1)))
      .filter(Boolean);

    if (!sections.length) return;

    function activationThresholdPx() {
      const head = document.querySelector(".lab-head");
      const h = head ? head.getBoundingClientRect().height : 76;
      return Math.round(Math.min(h + 32, 140));
    }

    function computeActiveSectionId() {
      const docEl = document.documentElement;
      const scrollBottom = window.scrollY + window.innerHeight;
      if (scrollBottom >= docEl.scrollHeight - 12) {
        return sections[sections.length - 1].id;
      }

      const threshold = activationThresholdPx();
      let activeId = sections[0].id;
      for (const sec of sections) {
        const top = sec.getBoundingClientRect().top;
        if (top <= threshold) activeId = sec.id;
      }
      return activeId;
    }

    function setActive(id) {
      if (!id) return;
      links.forEach((a) => {
        const hrefId = a.getAttribute("href").slice(1);
        const on = hrefId === id;
        a.classList.toggle("is-active", on);
        if (on) {
          a.setAttribute("aria-current", "true");
        } else {
          a.removeAttribute("aria-current");
        }
      });
    }

    let ticking = false;
    function syncFromScroll() {
      if (ticking) return;
      ticking = true;
      requestAnimationFrame(() => {
        ticking = false;
        setActive(computeActiveSectionId());
      });
    }

    window.addEventListener("scroll", syncFromScroll, { passive: true });
    window.addEventListener("resize", syncFromScroll, { passive: true });

    links.forEach((a) => {
      a.addEventListener("click", () => {
        const id = a.getAttribute("href").slice(1);
        requestAnimationFrame(() => setActive(id));
        setTimeout(() => setActive(computeActiveSectionId()), 280);
      });
    });

    window.addEventListener("hashchange", () => {
      const hid = location.hash.slice(1);
      if (hid && document.getElementById(hid)) setActive(hid);
    });

    const startHash = location.hash.slice(1);
    if (startHash && document.getElementById(startHash)) {
      setActive(startHash);
    } else {
      setActive(computeActiveSectionId());
    }
    syncFromScroll();
  }

  function initTilt() {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const strength = 10;

    document.querySelectorAll(".js-tilt").forEach((el) => {
      el.addEventListener("pointermove", (e) => {
        const r = el.getBoundingClientRect();
        const px = (e.clientX - r.left) / r.width - 0.5;
        const py = (e.clientY - r.top) / r.height - 0.5;
        el.style.transform = `perspective(720px) rotateX(${-py * strength}deg) rotateY(${px * strength}deg) translateZ(4px)`;
      });

      el.addEventListener("pointerleave", () => {
        el.style.transform = "";
      });
    });
  }

